import { FloodDecisionInputPayload } from './flood-decision-service';

export interface ChatMessage {
  role: 'user' | 'assistant' | 'system';
  content: string;
}

export interface ChatbotLLMResponse {
  answer: string;
  provider: 'online' | 'offline';
  modelName: string;
  latencyMs: number;
}

const NVIDIA_NIM_ENDPOINT = 'https://integrate.api.nvidia.com/v1/chat/completions';
const NVIDIA_MODEL_ID = 'nvidia/nemotron-3-ultra-550b-a55b';
const NVIDIA_TIMEOUT_MS = 15000; // 15-second timeout for NVIDIA NIM API response

const OLLAMA_ENDPOINT = process.env.OLLAMA_ENDPOINT || 'http://localhost:11434/api/chat';
const OLLAMA_MODEL_ID = process.env.OLLAMA_MODEL || 'deepseek-r1:1.5b';
const OLLAMA_TIMEOUT_MS = 60000; // 20-second timeout for local model inference

/**
 * Builds standard system prompt enforcing system data constraints & proactive follow-up behavior.
 */
export function buildChatbotSystemPrompt(contextPayload: FloodDecisionInputPayload): string {
  const jsonContext = JSON.stringify(contextPayload, null, 2);

  return `You are SURGE AI, the official urban flood intelligence assistant for AquaAlert / Surge.

SYSTEM TELEMETRY & LIVE CONTEXT (ALREADY-KNOWN FACT):
${jsonContext}

STRICT OPERATIONAL RULES & CONSTRAINTS:
1. NUMERICAL TRUTH: You must NEVER invent, estimate, predict, or alter any numeric value (rainfall mm/hr, water depth cm, elevation m, confidence %, or surcharging %). All real numbers you mention MUST be copied verbatim from the system context above.
2. NO INTERNET RETRIEVAL: You have NO access to external weather APIs or internet searches. If a user asks for information not present in the system context (e.g. detailed regional forecasts for unmonitored cities), state plainly: "That information is not available in current system telemetry." Never guess or fabricate plausible data.
3. PROACTIVE CLARIFYING FOLLOW-UPS: If a user asks an ambiguous safety question (e.g. "Is it safe to drive?", "Can I travel?", "Is my route clear?") without specifying their exact location, neighborhood, or vehicle type (hatchback, sedan, SUV, truck):
   - DO NOT make assumptions or give a generic blanket guarantee.
   - PROACTIVELY ASK 1–2 brief clarifying follow-up questions (e.g., "Which area or road corridor are you planning to travel through, and what type of vehicle will you be driving?").
4. CONVERSATIONAL STATE & TONE: Maintain professional, clear, calm, safety-oriented language appropriate for municipal crisis response. Keep answers concise and bullet-pointed where helpful.

Always output clean markdown formatted text. Do NOT wrap output in JSON.`;
}

/**
 * Strips reasoning tokens (<think>...</think>) often generated by DeepSeek R1 models
 * before delivering clean text to the end user.
 */
function cleanDeepSeekR1Output(text: string): string {
  if (!text) return '';
  return text.replace(/<think>[\s\S]*?<\/think>/gi, '').trim();
}

/**
 * Calls Online NVIDIA NIM API with DeepSeek R1 model.
 */
async function callNVIDIAProvider(
  messages: ChatMessage[],
  systemPrompt: string
): Promise<{ answer: string; modelName: string }> {
  const apiKey = process.env.NVIDIA_API_KEY;
  if (!apiKey) {
    throw new Error('NVIDIA_API_KEY is not configured on server.');
  }

  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), NVIDIA_TIMEOUT_MS);

  try {
    const formattedMessages: ChatMessage[] = [
      { role: 'system', content: systemPrompt },
      ...messages.filter(m => m.role !== 'system'),
    ];

    const response = await fetch(NVIDIA_NIM_ENDPOINT, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${apiKey}`,
        Accept: 'text/event-stream',
      },
      signal: controller.signal,
      body: JSON.stringify({
        model: NVIDIA_MODEL_ID,
        messages: formattedMessages,
        temperature: 0.7,
        max_tokens: 2048,
        stream: true,
      }),
    });

    if (!response.ok) {
      clearTimeout(timeoutId);
      const errText = await response.text().catch(() => '');
      throw new Error(`NVIDIA NIM API error (${response.status}): ${errText.slice(0, 150)}`);
    }

    if (!response.body) {
      clearTimeout(timeoutId);
      throw new Error('NVIDIA NIM API returned empty stream body.');
    }

    const reader = response.body.getReader();
    const decoder = new TextDecoder();
    let accumulatedContent = '';
    let accumulatedReasoning = '';
    let buffer = '';

    while (true) {
      const { done, value } = await reader.read();
      if (done) break;

      buffer += decoder.decode(value, { stream: true });
      const lines = buffer.split('\n');
      buffer = lines.pop() || '';

      for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith(':')) continue;
        if (trimmed === 'data: [DONE]') break;

        if (trimmed.startsWith('data: ')) {
          try {
            const parsed = JSON.parse(trimmed.slice(6));
            const delta = parsed.choices?.[0]?.delta;
            if (delta?.content) {
              accumulatedContent += delta.content;
            }
            if (delta?.reasoning_content) {
              accumulatedReasoning += delta.reasoning_content;
            }
          } catch (e) {
            // Ignore partial SSE chunk parse error
          }
        }
      }
    }

    clearTimeout(timeoutId);

    const finalRaw = accumulatedContent.trim() || accumulatedReasoning.trim();
    const answer = cleanDeepSeekR1Output(finalRaw);

    if (!answer) {
      throw new Error('NVIDIA NIM returned empty response text.');
    }

    return { answer, modelName: `NVIDIA NIM (${NVIDIA_MODEL_ID})` };
  } catch (err) {
    clearTimeout(timeoutId);
    throw err;
  }
}

/**
 * Calls Offline Local Ollama REST API with DeepSeek R1 1.5B model.
 */
async function callOllamaProvider(
  messages: ChatMessage[],
  systemPrompt: string
): Promise<{ answer: string; modelName: string }> {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), OLLAMA_TIMEOUT_MS);

  try {
    const formattedMessages: ChatMessage[] = [
      { role: 'system', content: systemPrompt },
      ...messages.filter(m => m.role !== 'system'),
    ];

    const response = await fetch(OLLAMA_ENDPOINT, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      signal: controller.signal,
      body: JSON.stringify({
        model: OLLAMA_MODEL_ID,
        stream: false,
        messages: formattedMessages,
        options: {
          temperature: 0.2,
        },
      }),
    });

    clearTimeout(timeoutId);

    if (!response.ok) {
      throw new Error(`Ollama API error (${response.status})`);
    }

    const data = await response.json();
    const rawContent = data?.message?.content || data?.response || '';
    const answer = cleanDeepSeekR1Output(rawContent);

    if (!answer) {
      throw new Error('Ollama returned empty response.');
    }

    return { answer, modelName: `Local Ollama (${OLLAMA_MODEL_ID})` };
  } catch (err: any) {
    clearTimeout(timeoutId);
    throw new Error(`Ollama offline model failed: ${err.message || 'connection refused'}`);
  }
}

/**
 * Main entry point for generating chatbot responses with dual-provider fallback.
 * Attempt 1: NVIDIA NIM hosted DeepSeek R1 (7-second timeout).
 * Attempt 2: Local Ollama deepseek-r1:1.5b (zero-network resilience fallback).
 */
export async function generateChatbotResponse(
  messages: ChatMessage[],
  contextPayload: FloodDecisionInputPayload
): Promise<ChatbotLLMResponse> {
  const startTime = Date.now();
  const systemPrompt = buildChatbotSystemPrompt(contextPayload);

  // Attempt 1: Online NVIDIA NIM hosted DeepSeek R1
  try {
    const onlineResult = await callNVIDIAProvider(messages, systemPrompt);
    return {
      answer: onlineResult.answer,
      provider: 'online',
      modelName: onlineResult.modelName,
      latencyMs: Date.now() - startTime,
    };
  } catch (onlineErr: any) {
    console.warn(`[Chatbot LLM] Online NVIDIA NIM provider failed (${onlineErr.message}). Falling back to local Ollama...`);
  }

  // Attempt 2: Offline Local Ollama deepseek-r1:1.5b
  try {
    const offlineResult = await callOllamaProvider(messages, systemPrompt);
    return {
      answer: offlineResult.answer,
      provider: 'offline',
      modelName: offlineResult.modelName,
      latencyMs: Date.now() - startTime,
    };
  } catch (offlineErr: any) {
    console.error(`[Chatbot LLM] Both Online and Offline LLM providers failed (${offlineErr.message}). Generating fallback message.`);
    
    // Deterministic safety fallback if both AI providers are unreachable
    const topRoad = contextPayload.flaggedRoadRisks[0];
    const topRoadSummary = topRoad
      ? `Highest risk corridor: ${topRoad.roadName} with depth of ${topRoad.waterDepthCm} cm (${topRoad.severity.toUpperCase()}).`
      : 'No critical road inundated in current telemetry.';

    return {
      answer: `System Notice: AI response generation is currently operating in static telemetry mode.\n\nActive City: ${contextPayload.cityName}\n${topRoadSummary}\nPrecipitation Source: ${contextPayload.precipitationSource.active.toUpperCase()} (${contextPayload.precipitationSource.confidencePct}% confidence).\n\nPlease refer directly to the live GIS map for real-time corridor status.`,
      provider: 'offline',
      modelName: 'Static System Telemetry Fallback',
      latencyMs: Date.now() - startTime,
    };
  }
}
